# ============================================================
# SATQUERY AI — REASONING AGENT
# ============================================================

def generate_grounded_answer(
    query,
    query_analysis,
    evidence_result
):
    """
    SATQuery AI Reasoning Agent

    Converts structured evidence from the previous agents
    into a grounded, human-readable response.

    IMPORTANT:
    This agent only uses evidence passed by the pipeline.
    It does not invent visual observations.
    """

    # --------------------------------------------------------
    # QUERY
    # --------------------------------------------------------

    agent = query_analysis.get(
        "agent",
        "VLM Reasoning"
    )

    task = query_analysis.get(
        "task",
        "General satellite-image analysis."
    )

    # --------------------------------------------------------
    # SATELLITE EVIDENCE
    # --------------------------------------------------------

    satellite = evidence_result.get(
        "satellite_evidence",
        {}
    )

    scene_id = satellite.get(
        "scene_id",
        "Unknown"
    )

    observation_date = satellite.get(
        "observation_date",
        "Unknown"
    )

    cloud_cover = satellite.get(
        "cloud_cover",
        "Unknown"
    )

    # --------------------------------------------------------
    # VISION EVIDENCE
    # --------------------------------------------------------

    vision = evidence_result.get(
        "vision_evidence",
        {}
    )

    vision_agent = vision.get(
        "agent",
        agent
    )

    findings = vision.get(
        "findings",
        []
    )

    vision_confidence = vision.get(
        "confidence",
        "UNKNOWN"
    )

    # --------------------------------------------------------
    # OBJECT DETECTION EVIDENCE
    # --------------------------------------------------------

    detection = evidence_result.get(
        "object_detection_evidence",
        {}
    )

    detection_available = detection.get(
        "detection_available",
        False
    )

    total_objects = detection.get(
        "total_objects",
        0
    )

    object_counts = detection.get(
        "object_counts",
        {}
    )

    detections = detection.get(
        "detections",
        []
    )

    # --------------------------------------------------------
    # OVERALL CONFIDENCE
    # --------------------------------------------------------

    confidence = evidence_result.get(
        "confidence",
        "INSUFFICIENT"
    )

    # --------------------------------------------------------
    # BUILD ANSWER
    # --------------------------------------------------------

    answer = []

    answer.append(
        "SATQuery AI analysed the query using "
        f"the {vision_agent}."
    )

    answer.append(
        f"Task: {task}"
    )

    # --------------------------------------------------------
    # SATELLITE INFORMATION
    # --------------------------------------------------------

    answer.append(
        f"Satellite scene: {scene_id}"
    )

    answer.append(
        f"Observation date: {observation_date}"
    )

    if cloud_cover != "Unknown":

        answer.append(
            f"Cloud cover: {cloud_cover}%"
        )

    # --------------------------------------------------------
    # OBJECT DETECTION ANSWER
    # --------------------------------------------------------

    if detection_available:

        answer.append(
            "Visual detection evidence:"
        )

        answer.append(
            f"Total detected objects: {total_objects}"
        )

        if object_counts:

            for object_name, count in (
                object_counts.items()
            ):

                answer.append(
                    f"• {object_name}: {count}"
                )

        if detections:

            answer.append(
                "Bounding-box detections were "
                "generated by the Object Detection Agent."
            )

    # --------------------------------------------------------
    # VLM ANSWER
    # --------------------------------------------------------

    elif vision_agent == "VLM Reasoning":

        if findings:

            answer.append(
                "Visual reasoning findings:"
            )

            for finding in findings:

                answer.append(
                    f"• {finding}"
                )

    # --------------------------------------------------------
    # OTHER SPECIALIST AGENTS
    # --------------------------------------------------------

    else:

        if findings:

            answer.append(
                "Evidence from the Vision Agent:"
            )

            for finding in findings:

                answer.append(
                    f"• {finding}"
                )

    # --------------------------------------------------------
    # CONFIDENCE
    # --------------------------------------------------------

    answer.append(
        f"Confidence: {confidence}"
    )

    # --------------------------------------------------------
    # LIMITATIONS
    # --------------------------------------------------------

    if detection_available:

        answer.append(
            "Note: Object detections are preliminary "
            "and should not be treated as precise "
            "geospatial measurements."
        )

    elif vision_agent == "VLM Reasoning":

        if vision_confidence == "LOW":

            answer.append(
                "Note: The visual evidence is limited, "
                "so the result should be treated cautiously."
            )

    elif not findings:

        answer.append(
            "Note: No verified visual findings were "
            "available for this query."
        )

    # --------------------------------------------------------
    # RETURN
    # --------------------------------------------------------

    return {

        "query": query,

        "agent": "Reasoning Agent",

        "confidence": confidence,

        "answer": "\n\n".join(answer),

        "grounded": True

    }